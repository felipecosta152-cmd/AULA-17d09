

#Peça um número e informe se ele é positivo,
# negativo ou igual a zero.

numero1 = int(input("Digite um número: "))
if numero1 > 0:
    
    print (f"O primeiro número ({numero1}) é positivo") 
elif numero1 == 0:
    
    print (f"o numero ({numero1}) é igual a zero ")
else:
    print(f"o numero ({numero1}) é negativo" )
    
   
        






    